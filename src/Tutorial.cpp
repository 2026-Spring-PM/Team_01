#include "Tutorial.h"

Tutorial::Tutorial() {
    build_dialogues();
}

const char* Tutorial::npc_name() {
    return "씨앗 할머니";
}

int Tutorial::total_steps() const {
    return static_cast<int>(dialogues_.size());
}

std::string Tutorial::current_title() const {
    if (completed_ || step_ >= total_steps()) return "";
    return dialogues_[step_].title;
}

std::string Tutorial::current_dialogue() const {
    if (completed_ || step_ >= total_steps()) return "";
    return dialogues_[step_].text;
}

void Tutorial::advance() {
    if (completed_) return;
    ++step_;
    if (step_ >= total_steps()) completed_ = true;
}

